//! # cf-totp —— TOTP 动态口令
//!
//! 按 RFC 6238 生成 TOTP，解析 otpauth:// URI。
//!
//! ## 对应设计文档
//!
//! - `docs/03-详细设计.md` §7（TOTP 实现）
//! - RFC 6238 Appendix B（18 条标准测试向量，见 §7.2）
//!
//! ## 职责边界
//!
//! - **不存储密钥**（那是 `cf-store` 的职责），只做计算；
//! - QR 解码不在本 crate —— 用平台原生能力
//!   （Android: zxing / ML Kit；macOS: Vision 框架）；
//! - **不处理 `hotp://`** —— 明确报错，不静默当 totp 处理。
//!
//! 验收门槛：RFC 6238 Appendix B 的 18 条测试向量必须全部通过，
//! 若某条不通过说明实现有 bug，**不允许通过调测试向量来「修好」**。
//!
//! ## 状态
//!
//! **未实现** —— 计划在 **M1** 阶段实现。
//! 参见 `README.md`「当前状态」与 `docs/04-系统设计.md` §10.1（阶段划分）。
//!
//! 本文件当前只声明模块意图，不含任何可调用接口。
//! 这样做是刻意的：宁可目录里是空的，也不要一个 `todo!()` 占位的假接口。

