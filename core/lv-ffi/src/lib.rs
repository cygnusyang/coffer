//! # lv-ffi —— FFI 绑定层
//!
//! 通过 UniFFI 暴露接口给 Kotlin / Swift，负责类型与错误映射。
//!
//! ## 对应设计文档
//!
//! - `docs/02-概要设计.md` §5（FFI 接口概要）
//! - `docs/03-详细设计.md` §5（FFI 接口清单）
//! - `docs/03-详细设计.md` §5.5（平台回调）
//!
//! ## 职责边界
//!
//! **不含业务逻辑** —— 只做类型映射、错误映射与接口暴露。
//!
//! 设计原则：**粗粒度、面向用例**。不为 `get_field()` 这种细粒度操作
//! 暴露接口，而是暴露「解锁保险库」「搜索条目」「执行导入」这类用例。
//! 理由：细粒度接口会导致 UI 侧大量往返调用，且难以保证事务与
//! 权限检查的一致性（见 §5）。
//!
//! 本 crate 是 M0 第 ② 项（UniFFI 双端打通）的验证载体。
//!
//! ## 状态
//!
//! **未实现** —— 计划在 **M0/M1** 阶段实现。
//! 参见 `README.md`「当前状态」与 `docs/04-系统设计.md` §10.1（阶段划分）。
//!
//! 本文件当前只声明模块意图，不含任何可调用接口。
//! 这样做是刻意的：宁可目录里是空的，也不要一个 `todo!()` 占位的假接口。

