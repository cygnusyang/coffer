//! # lv-session —— 会话与应用服务
//!
//! 解锁 / 锁定、用例编排、权限门禁、空闲计时判定。
//!
//! ## 对应设计文档
//!
//! - `docs/02-概要设计.md` §4.3（会话与锁定模型）
//! - `docs/03-详细设计.md` §11（内存安全与自动锁定实现）
//!
//! ## 职责边界
//!
//! 本 crate 是**唯一持有 DEK 的模块**。所有数据访问用例
//! 必须先通过 `require_unlocked()` 检查，未解锁时返回 `VaultLocked`。
//!
//! **该检查必须在 Rust 侧强制执行，不能依赖 UI 层的状态管理**
//! —— UI 状态可被绕过，Rust 侧不行（见 §4.3 门禁规则）。
//!
//! 定时器放在平台侧：本 crate 只提供 `set_last_activity(ts)` 与
//! `is_expired(now, threshold)` 两个纯函数，保证时间可注入、可测试。
//!
//! ## 状态
